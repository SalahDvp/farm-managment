// Lightweight, dependency-free internationalization.
//
// `dict` holds one flat key→string map per locale. English is the source of
// truth; any key missing from another locale falls back to English, then to the
// raw key. `translate` also interpolates `{var}` placeholders.

export type Locale = 'en' | 'fr' | 'ar'
export type Dir = 'ltr' | 'rtl'

export const LOCALES: { code: Locale; native: string; short: string; dir: Dir }[] = [
  { code: 'en', native: 'English', short: 'EN', dir: 'ltr' },
  { code: 'fr', native: 'Français', short: 'FR', dir: 'ltr' },
  { code: 'ar', native: 'العربية', short: 'AR', dir: 'rtl' },
]

export const DEFAULT_LOCALE: Locale = 'en'
export const STORAGE_KEY = 'fieldwise.locale'

export function dirFor(locale: Locale): Dir {
  return LOCALES.find((l) => l.code === locale)?.dir ?? 'ltr'
}

